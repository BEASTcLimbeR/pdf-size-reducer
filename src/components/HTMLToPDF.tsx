'use client';

import { useState, useCallback } from 'react';
import { Upload, Download, AlertCircle, CheckCircle, RotateCcw, Globe, FileText } from 'lucide-react';
import { PDFDocument, rgb } from 'pdf-lib';

interface ConversionResult {
  convertedFile: Uint8Array;
  originalSize: number;
  convertedSize: number;
  pagesCount: number;
}

export default function HTMLToPDF({ onReset }: { onReset: () => void }) {
  const [htmlContent, setHtmlContent] = useState('');
  const [url, setUrl] = useState('');
  const [conversionMode, setConversionMode] = useState<'html' | 'url'>('html');
  const [isConverting, setIsConverting] = useState(false);
  const [result, setResult] = useState<ConversionResult | null>(null);
  const [error, setError] = useState<string | null>(null);

  const handleConvert = useCallback(async () => {
    if (!htmlContent.trim() && conversionMode === 'html') {
      setError('Please enter HTML content or provide a URL');
      return;
    }

    if (!url.trim() && conversionMode === 'url') {
      setError('Please enter a valid URL');
      return;
    }

    setIsConverting(true);
    setError(null);

    try {
      // Simulate conversion process
      await new Promise(resolve => setTimeout(resolve, 2000));

      // Create a new PDF document
      const pdfDoc = await PDFDocument.create();
      const page = pdfDoc.addPage([595.28, 841.89]); // A4 size
      
      // Add title
      const font = await pdfDoc.embedFont('Helvetica');
      page.drawText('HTML to PDF Conversion', {
        x: 50,
        y: 800,
        size: 20,
        font: font,
        color: rgb(0, 0, 0),
      });

      // Add content based on mode
      if (conversionMode === 'html') {
        // Simulate HTML content processing
        const lines = htmlContent.split('\n').slice(0, 30); // Limit to 30 lines
        let yPosition = 750;
        
        for (const line of lines) {
          if (yPosition < 50) break; // Prevent overflow
          
          const cleanLine = line.replace(/<[^>]*>/g, '').trim(); // Remove HTML tags
          if (cleanLine) {
            page.drawText(cleanLine, {
              x: 50,
              y: yPosition,
              size: 12,
              font: font,
              color: rgb(0, 0, 0),
            });
            yPosition -= 20;
          }
        }
      } else {
        // URL mode
        page.drawText(`URL: ${url}`, {
          x: 50,
          y: 750,
          size: 12,
          font: font,
          color: rgb(0, 0, 0),
        });
        
        page.drawText('Note: This is a simulated conversion. In a real implementation,', {
          x: 50,
          y: 720,
          size: 10,
          font: font,
          color: rgb(0.5, 0.5, 0.5),
        });
        
        page.drawText('this would fetch the webpage and convert it to PDF.', {
          x: 50,
          y: 700,
          size: 10,
          font: font,
          color: rgb(0.5, 0.5, 0.5),
        });
      }

      // Add footer
      page.drawText('Generated by DocNestly', {
        x: 50,
        y: 30,
        size: 10,
        font: font,
        color: rgb(0.5, 0.5, 0.5),
      });

      pdfDoc.setCreator('DocNestly - HTML to PDF');
      pdfDoc.setTitle('HTML to PDF Conversion');
      pdfDoc.setSubject('Converted HTML content to PDF');

      const pdfBytes = await pdfDoc.save();
      
      const conversionResult: ConversionResult = {
        convertedFile: pdfBytes,
        originalSize: conversionMode === 'html' ? htmlContent.length : url.length,
        convertedSize: pdfBytes.length,
        pagesCount: 1,
      };

      setResult(conversionResult);
    } catch (err) {
      setError('Failed to convert HTML to PDF. Please try again.');
      console.error('Conversion error:', err);
    } finally {
      setIsConverting(false);
    }
  }, [htmlContent, url, conversionMode]);

  const handleDownload = useCallback(() => {
    if (!result) return;

    const arrayBuffer = result.convertedFile.buffer.slice(0) as ArrayBuffer;
    const blob = new Blob([arrayBuffer], { type: 'application/pdf' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'converted-html.pdf';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }, [result]);

  const handleReset = useCallback(() => {
    setHtmlContent('');
    setUrl('');
    setResult(null);
    setError(null);
    setIsConverting(false);
  }, []);

  return (
    <div className="max-w-4xl mx-auto">
      <div className="bg-white dark:bg-gray-800 rounded-lg shadow-sm border border-gray-200 dark:border-gray-700 p-6 sm:p-8">
        <div className="text-center mb-8">
          <div className="w-16 h-16 bg-blue-100 dark:bg-blue-900 rounded-full flex items-center justify-center mx-auto mb-4">
            <Globe className="h-8 w-8 text-blue-600 dark:text-blue-400" />
          </div>
          <h2 className="text-2xl sm:text-3xl font-bold text-gray-900 dark:text-white mb-2">
            HTML to PDF Converter
          </h2>
          <p className="text-gray-600 dark:text-gray-300">
            Convert HTML content or web pages to PDF documents
          </p>
        </div>

        {!result ? (
          <div className="space-y-6">
            {/* Conversion Mode Selection */}
            <div>
              <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-3">
                Choose Conversion Mode
              </label>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                <button
                  onClick={() => setConversionMode('html')}
                  className={`p-4 rounded-lg border-2 transition-colors ${
                    conversionMode === 'html'
                      ? 'border-blue-500 bg-blue-50 dark:bg-blue-900/20'
                      : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
                  }`}
                >
                  <FileText className="h-6 w-6 mx-auto mb-2 text-blue-600" />
                  <div className="font-medium">HTML Content</div>
                  <div className="text-sm text-gray-500">Paste HTML code</div>
                </button>
                <button
                  onClick={() => setConversionMode('url')}
                  className={`p-4 rounded-lg border-2 transition-colors ${
                    conversionMode === 'url'
                      ? 'border-blue-500 bg-blue-50 dark:bg-blue-900/20'
                      : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
                  }`}
                >
                  <Globe className="h-6 w-6 mx-auto mb-2 text-blue-600" />
                  <div className="font-medium">Web URL</div>
                  <div className="text-sm text-gray-500">Enter website URL</div>
                </button>
              </div>
            </div>

            {/* HTML Content Input */}
            {conversionMode === 'html' && (
              <div>
                <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
                  HTML Content
                </label>
                <textarea
                  value={htmlContent}
                  onChange={(e) => setHtmlContent(e.target.value)}
                  placeholder="Paste your HTML content here..."
                  className="w-full h-64 p-4 border border-gray-300 dark:border-gray-600 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-transparent resize-none dark:bg-gray-700 dark:text-white"
                />
                <p className="text-sm text-gray-500 mt-2">
                  Enter the HTML content you want to convert to PDF
                </p>
              </div>
            )}

            {/* URL Input */}
            {conversionMode === 'url' && (
              <div>
                <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
                  Website URL
                </label>
                <input
                  type="url"
                  value={url}
                  onChange={(e) => setUrl(e.target.value)}
                  placeholder="https://example.com"
                  className="w-full p-4 border border-gray-300 dark:border-gray-600 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-transparent dark:bg-gray-700 dark:text-white"
                />
                <p className="text-sm text-gray-500 mt-2">
                  Enter the URL of the webpage you want to convert to PDF
                </p>
              </div>
            )}

            {/* Error Message */}
            {error && (
              <div className="flex items-center p-4 bg-red-50 dark:bg-red-900/20 border border-red-200 dark:border-red-800 rounded-lg">
                <AlertCircle className="h-5 w-5 text-red-500 mr-3" />
                <span className="text-red-700 dark:text-red-300">{error}</span>
              </div>
            )}

            {/* Convert Button */}
            <button
              onClick={handleConvert}
              disabled={isConverting || (!htmlContent.trim() && conversionMode === 'html') || (!url.trim() && conversionMode === 'url')}
              className="w-full bg-blue-600 hover:bg-blue-700 disabled:bg-gray-400 text-white font-medium py-3 px-6 rounded-lg transition-colors flex items-center justify-center"
            >
              {isConverting ? (
                <>
                  <div className="animate-spin rounded-full h-5 w-5 border-b-2 border-white mr-2"></div>
                  Converting...
                </>
              ) : (
                <>
                  <Globe className="h-5 w-5 mr-2" />
                  Convert to PDF
                </>
              )}
            </button>
          </div>
        ) : (
          <div className="text-center space-y-6">
            <div className="flex items-center justify-center w-16 h-16 bg-green-100 dark:bg-green-900 rounded-full mx-auto">
              <CheckCircle className="h-8 w-8 text-green-600 dark:text-green-400" />
            </div>
            
            <div>
              <h3 className="text-xl font-semibold text-gray-900 dark:text-white mb-2">
                Conversion Complete!
              </h3>
              <p className="text-gray-600 dark:text-gray-300">
                Your HTML has been successfully converted to PDF
              </p>
            </div>

            <div className="bg-gray-50 dark:bg-gray-700 rounded-lg p-4">
              <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 text-sm">
                <div>
                  <div className="text-gray-500 dark:text-gray-400">Original Size</div>
                  <div className="font-semibold text-gray-900 dark:text-white">
                    {result.originalSize.toLocaleString()} characters
                  </div>
                </div>
                <div>
                  <div className="text-gray-500 dark:text-gray-400">PDF Size</div>
                  <div className="font-semibold text-gray-900 dark:text-white">
                    {(result.convertedSize / 1024).toFixed(2)} KB
                  </div>
                </div>
                <div>
                  <div className="text-gray-500 dark:text-gray-400">Pages</div>
                  <div className="font-semibold text-gray-900 dark:text-white">
                    {result.pagesCount}
                  </div>
                </div>
              </div>
            </div>

            <div className="flex flex-col sm:flex-row gap-4 justify-center">
              <button
                onClick={handleDownload}
                className="inline-flex items-center px-6 py-3 bg-blue-600 hover:bg-blue-700 text-white font-medium rounded-lg transition-colors"
              >
                <Download className="h-5 w-5 mr-2" />
                Download PDF
              </button>
              <button
                onClick={handleReset}
                className="inline-flex items-center px-6 py-3 bg-gray-600 hover:bg-gray-700 text-white font-medium rounded-lg transition-colors"
              >
                <RotateCcw className="h-5 w-5 mr-2" />
                Convert Another
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
